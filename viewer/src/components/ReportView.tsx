import type { MissionReport } from "@walle/contracts";

interface ReportViewProps {
  report: MissionReport;
}

export function ReportView({ report }: ReportViewProps) {
  const confPct = Math.round(report.inference.confidence * 100);

  return (
    <div className="view-stack">
      <section className="card">
        <h2 className="card-title">Outcome</h2>
        <div className="report-grid">
          <div className="stat">
            <span className="label">Terminal</span>
            <span className={`badge ${report.outcome.successful ? "success" : "danger"}`}>
              {report.outcome.terminal}
            </span>
          </div>
          <div className="stat">
            <span className="label">Successful</span>
            <span className="value small">{report.outcome.successful ? "yes" : "no"}</span>
          </div>
          <div className="stat">
            <span className="label">Steps</span>
            <span className="value small">{report.outcome.steps}</span>
          </div>
          <div className="stat">
            <span className="label">Ticks used</span>
            <span className="value small">{report.outcome.ticks_used}</span>
          </div>
          <div className="stat">
            <span className="label">Battery used</span>
            <span className="value small">{report.outcome.battery_used}</span>
          </div>
          <div className="stat">
            <span className="label">Battery remaining</span>
            <span className="value small">{report.outcome.battery_remaining}</span>
          </div>
        </div>
        <p className="decision-reason" style={{ marginTop: 16 }}>
          planner <code>{report.planner}</code> · seed <code>{report.seed}</code> · generated by{" "}
          <code>{report.generated_by}</code>
        </p>
      </section>

      <section className="card">
        <h2 className="card-title">Evidence ({report.evidence.length})</h2>
        {report.evidence.length === 0 ? (
          <p className="decision-reason">No evidence collected.</p>
        ) : (
          <ul className="evidence-list" data-testid="evidence-list">
            {report.evidence.map((item) => (
              <li key={item.clue_id} className="evidence-item">
                <span className="clue-kind">{item.kind.replace("_", " ")}</span>
                <div>
                  <p className="desc">{item.description}</p>
                  <p className="meta">
                    {item.clue_id} · [{item.pos[0]}, {item.pos[1]}] · tick {item.tick}
                  </p>
                </div>
              </li>
            ))}
          </ul>
        )}
      </section>

      <section className="card">
        <h2 className="card-title">Inference</h2>
        <div className="report-grid">
          <div className="stat">
            <span className="label">EVE location</span>
            <span className="value small">
              [{report.inference.eve_location[0]}, {report.inference.eve_location[1]}]
            </span>
          </div>
          <div className="stat">
            <span className="label">Status</span>
            <span className="value small">{report.inference.status}</span>
          </div>
          <div className="stat">
            <span className="label">Confidence</span>
            <span className="value small">{report.inference.confidence.toFixed(2)}</span>
          </div>
        </div>
        <div className="confidence-meter" data-testid="confidence-meter">
          <div className="meter-track">
            <div className="meter-fill" style={{ width: `${confPct}%` }} />
          </div>
          <span className="mono" style={{ fontSize: 11, color: "var(--text-faint)" }}>
            {confPct}%
          </span>
        </div>
        <p className="decision-reason">{report.inference.recommended_next_step}</p>
      </section>

      <section className="card">
        <h2 className="card-title">Strategy</h2>
        <ul className="phase-list">
          {report.strategy.phases.map((phase) => (
            <li key={phase.name} className="phase-item">
              <div>
                <span className="name">{phase.name.replace("_", " ")}</span>
                <span className="range">
                  ticks {phase.start_tick}–{phase.end_tick}
                </span>
              </div>
              <p className="note">{phase.note}</p>
            </li>
          ))}
        </ul>
        <div className="decision-meta" style={{ marginTop: 12 }}>
          <span className="badge">recharges: {report.strategy.recharges}</span>
          <span className="badge">scans: {report.strategy.scans}</span>
          <span className="badge">
            turn-back tick: {report.strategy.turn_back_tick ?? "—"}
          </span>
        </div>
      </section>

      <section className="card" aria-label="Evaluator-only ground truth">
        <h2 className="card-title evaluator-badge">
          Evaluation
          <span className="badge amber">evaluator-only</span>
        </h2>
        <p className="decision-reason" style={{ marginTop: 0 }}>
          Ground-truth metrics below are computed by the environment evaluator. They are never
          exposed to any planner.
        </p>
        <div className="report-grid">
          <div className="stat">
            <span className="label">True EVE pos</span>
            <span className="value small">
              [{report.evaluation.true_eve_pos[0]}, {report.evaluation.true_eve_pos[1]}]
            </span>
          </div>
          <div className="stat">
            <span className="label">Localization error</span>
            <span className="value small">{report.evaluation.localization_error.toFixed(2)}</span>
          </div>
          <div className="stat">
            <span className="label">Clues found</span>
            <span className="value small">
              {report.evaluation.clues_found} / {report.evaluation.clues_total}
            </span>
          </div>
          <div className="stat">
            <span className="label">Invalid actions</span>
            <span className="value small">{report.evaluation.invalid_action_count}</span>
          </div>
          <div className="stat">
            <span className="label">Failed claims</span>
            <span className="value small">{report.evaluation.failed_claims}</span>
          </div>
        </div>
      </section>

      {report.notes.length > 0 && (
        <section className="card">
          <h2 className="card-title">Notes</h2>
          <ul className="evidence-list">
            {report.notes.map((note) => (
              <li key={note} className="decision-reason" style={{ margin: 0 }}>
                {note}
              </li>
            ))}
          </ul>
        </section>
      )}
    </div>
  );
}
